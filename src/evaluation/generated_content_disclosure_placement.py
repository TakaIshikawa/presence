"""Check generated-content disclosure placement."""
from __future__ import annotations
from collections import Counter
from typing import Any
from ._batch_report_common import *
ARTIFACT_TYPE="generated_content_disclosure_placement"; DEFAULT_LIMIT=50; DEFAULT_ALLOWED_OFFSET=240
PHRASES=("ai-generated","generated by ai","created with ai","assisted by ai","synthetic content")
SHORT={"x","twitter","tiktok","shorts","sms"}
def build_generated_content_disclosure_placement_report(rows:list[dict[str,Any]],*,allowed_offset:int=DEFAULT_ALLOWED_OFFSET,limit:int=DEFAULT_LIMIT,missing_tables=None,missing_columns=None,now=None):
    non_negative("allowed_offset",allowed_offset); positive("limit",limit); findings=[]; counts=Counter()
    for r in rows:
        text=clean(r.get("body") or r.get("content") or r.get("text")); channel=lower(r.get("channel") or r.get("platform"),"unknown")
        label,off=_find_label(text); length=len(text); short=channel in SHORT or length<=280; max_off=min(80,allowed_offset) if short else allowed_offset
        if off is None: status="missing"; counts[status]+=1
        elif off>max_off: status="late"; counts[status]+=1
        else: status="acceptable"; counts[status]+=1
        if status!="acceptable":
            findings.append({"content_id":r.get("content_id") or r.get("id"),"channel":channel,"platform":r.get("platform"),"label_text":label,"label_offset":off,"content_length":length,"placement_status":status,"recommended_action":"add disclosure near the beginning" if status=="missing" else "move disclosure earlier in the content"})
    findings.sort(key=lambda f:(f["placement_status"]!="missing",-(f["label_offset"] or 0),str(f["content_id"])))
    shown=findings[:limit]
    return {"artifact_type":ARTIFACT_TYPE,"generated_at":now_iso(now),"filters":{"allowed_offset":allowed_offset,"limit":limit},"summary":{"content_count":len(rows),"missing":counts["missing"],"late":counts["late"],"acceptable":counts["acceptable"],"finding_count":len(findings),"shown":len(shown)},"findings":shown,"missing_tables":sorted(missing_tables or []),"missing_columns":{k:sorted(v) for k,v in sorted((missing_columns or {}).items())},"empty_state":empty_state(findings,"All generated-content disclosures are acceptably placed.",schema_gap=bool(missing_tables or missing_columns))}
def _find_label(text):
    low=text.lower(); hits=[(low.find(p),p) for p in PHRASES if low.find(p)>=0]
    if not hits: return None,None
    off,label=min(hits); return label,off
def build_generated_content_disclosure_placement_report_from_db(db_or_conn:Any,**kw):
    conn=connection(db_or_conn); s=schema(conn); mt=[]; mc={}; rows=[]; table=None
    for t in ("generated_content","publications","published_posts"):
        if t in s: table=t; break
    if not table: mt.append("generated_content|publications|published_posts")
    else:
        c=s[table]
        if not ({"body","content","text"} & c): mc[table]=["body|content|text"]
        else: rows=load_table(conn,table,c,{"content_id":("id","content_id","generated_content_id"),"body":("body","content","text"),"channel":("channel","platform"),"platform":("platform",)})
    return build_generated_content_disclosure_placement_report(rows,missing_tables=mt,missing_columns=mc,**kw)
def format_generated_content_disclosure_placement_json(r): return json_dumps(r)
def format_generated_content_disclosure_placement_text(r):
    s=r["summary"]; lines=["Generated Content Disclosure Placement",f"Generated: {r['generated_at']}",f"Totals: content={s['content_count']} missing={s['missing']} late={s['late']} acceptable={s['acceptable']}"]
    if r["missing_tables"]: lines.append("Missing tables: "+", ".join(r["missing_tables"]))
    if r["missing_columns"]: lines.append("Missing columns: "+flatten_missing(r["missing_columns"]))
    if not r["findings"]: lines.append(r["empty_state"]["message"]); return "\n".join(lines)
    lines+=["","content_id | channel | status | offset"]
    for f in r["findings"]: lines.append(f"{f['content_id']} | {f['channel']} | {f['placement_status']} | {f['label_offset']}")
    return "\n".join(lines)
